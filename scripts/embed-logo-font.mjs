// Puts the logo font (Bariol Regular) into the plugin, so everyone sees the logo in Bariol:
//   node scripts/embed-logo-font.mjs path/to/bariol_regular.woff2
// Check the font's licence allows embedding it in a web page (a "webfont" licence) before publishing.
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file || !/\.(woff2?|otf|ttf)$/i.test(file)) {
    console.error('Usage: node scripts/embed-logo-font.mjs <bariol regular .woff2 / .woff / .otf / .ttf>');
    process.exit(1);
}
const ext = file.split('.').pop().toLowerCase();
const format = { woff2: 'woff2', woff: 'woff', otf: 'opentype', ttf: 'truetype' }[ext];
const mime = { woff2: 'font/woff2', woff: 'font/woff', otf: 'font/otf', ttf: 'font/ttf' }[ext];
const data = readFileSync(file).toString('base64');
const css = `@font-face{font-family:'racetrack-logo';font-style:normal;font-weight:400;font-display:swap;src:local('Bariol Regular'),local('Bariol-Regular'),url(data:${mime};base64,${data}) format('${format}');}`;
writeFileSync(new URL('../src/lib/logo-font.ts', import.meta.url), `// Generated by scripts/embed-logo-font.mjs: the logo's font (Bariol Regular), inside the plugin.\nexport const LOGO_FONT_CSS = ${JSON.stringify(css)};\n`);
console.log(`Logo font embedded (${Math.round(data.length / 1024)} KB). Rebuild the plugin.`);
